// ── Route handler ────────────────────────────────────────────────────────────

export async function POST(request: NextRequest) {
  console.log('[chat] ✅ Using NEW chat API — v3 streaming rewrite')

  let body: { messages?: Array<{ role: string; content: string }>; lang?: string }
  try {
    body = await request.json()
  } catch {
    return new Response('Invalid request body', { status: 400 })
  }

  const { messages = [], lang = 'zh' } = body
  const apiKey = process.env.GEMINI_API_KEY
  console.log('[chat] API key present:', !!apiKey, '| lang:', lang, '| messages:', messages.length)

  // No API key → return rich static fallback (still readable by the streaming reader)
  if (!apiKey) {
    return new Response(lang === 'en' ? FALLBACK_EN : FALLBACK_ZH, {
      headers: { 'Content-Type': 'text/plain; charset=utf-8' },
    })
  }

  const prompt = buildPrompt(messages, lang)

  try {
    const genAI = new GoogleGenerativeAI(apiKey)
    const model = genAI.getGenerativeModel({
      model: 'gemini-1.5-flash-latest',
      generationConfig: {
        maxOutputTokens: 600,
        temperature: 0.75,
      },
    })

    // Single generateContentStream call — no startChat, no history array, no role errors
    const streamResult = await model.generateContentStream(prompt)

    const encoder = new TextEncoder()
    const readable = new ReadableStream({
      async start(controller) {
        try {
          for await (const chunk of streamResult.stream) {
            const text = chunk.text()
            if (text) controller.enqueue(encoder.encode(text))
          }
        } catch (streamErr) {
          console.error('[chat:stream]', streamErr)
          const msg =
            lang === 'zh'
              ? '\n\n⚠️ 回答生成中断，请重试。'
              : '\n\n⚠️ Response interrupted. Please try again.'
          controller.enqueue(encoder.encode(msg))
        } finally {
          controller.close()
        }
      },
    })

    return new Response(readable, {
      headers: {
        'Content-Type': 'text/plain; charset=utf-8',
        'Cache-Control': 'no-cache, no-store',
        'X-Accel-Buffering': 'no', // disable Nginx/proxy buffering for streaming
      },
    })
  } catch (err) {
    console.error('[chat]', err)
    const msg =
      lang === 'zh'
        ? '**抱歉**，AI 服务暂时不可用，请稍后再试。\n\n⚠️ AI 问诊仅供参考，不构成医疗诊断。'
        : '**Sorry**, the AI service is temporarily unavailable. Please try again later.\n\n⚠️ For reference only, not medical advice.'
    return new Response(msg, {
      headers: { 'Content-Type': 'text/plain; charset=utf-8' },
    })
  }
}
